'use strict';

const fs = require('node:fs');
const path = require('node:path');
const sources = Object.freeze(['barcode-core.js', 'extract-core.js', 'image-core.js', 'samples.js', 'messages.js', 'app.js']);
const output = 'postmirror.bundle.js';

function bundleSource() {
  const header = '// Generated by node build.js. Edit the source files, then regenerate this file.\n';
  return header + sources.map(name => {
    const source = fs.readFileSync(path.join(__dirname, name), 'utf8').replace(/\r\n/g, '\n').trimEnd();
    return `\n// Source: ${name}\n${source}\n;\n`;
  }).join('');
}

if (require.main === module) {
  const expected = bundleSource();
  const target = path.join(__dirname, output);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== expected) {
      console.error(`${output} is out of date. Run npm run build before testing or publishing.`);
      process.exitCode = 1;
    }
  } else {
    fs.writeFileSync(target, expected, 'utf8');
    console.log(`Built ${output} from ${sources.length} local source files.`);
  }
}

module.exports = { sources, output, bundleSource };
